from pathlib import Path
root=Path('@ROOT@')
lib=(root/'apps/gui/src/library.rs').read_text()
watch=(root/'apps/gui/src/watch_table.rs').read_text()
def block(source, marker):
 start=source.index(marker); op=source.index('{',start); depth=1; pos=op+1
 while depth:
  depth+=(source[pos]=='{')-(source[pos]=='}'); pos+=1
 return source[start:pos]
structs=lib[lib.index('#[derive(Clone, Debug, Default, PartialEq)]'):lib.index('#[derive(Clone, Debug, Default, PartialEq)]\npub struct LibraryInfo')]
cols=lib[lib.index('#[derive(Clone, Copy, Debug, PartialEq, Eq)]\nenum LibraryColumn'):lib.index('pub struct LibraryTable')]
table=lib[lib.index('pub struct LibraryTable'):lib.index('    fn text(&self, row_ix: usize')]+ '}\n'
# Copied source is kept separate so the main agent can inspect it.
out='''// Generated by setup.py from the production sources at 5f4acbe.
// Only module imports and benchmark entry points are added.
use super::*;
'''+structs+cols+table+'''
pub fn run(albums: &[Arc<AlbumRow>], ops: &[Operation]) -> Vec<Vec<Projection>> {
 let mut table=LibraryTable::new();
 table.set_albums(albums.to_vec());
 let mut out=Vec::new();
 for op in ops {
  table.sort=op.column.and_then(LibraryColumn::at).map(|c|(c,if op.descending {ColumnSort::Descending}else{ColumnSort::Ascending}));
  table.set_filter(&op.filter);
  out.push(table.rows.iter().map(|a|project(a,a.length(),a.format())).collect());
 }
 out
}
pub fn raw_length(a:&AlbumRow)->f64 {a.length()}
pub fn raw_format(a:&AlbumRow)->String {a.format()}
pub fn raw_matches(a:&AlbumRow,s:&str)->bool {a.matches(s)}
'''
Path('@LAB@/src/library_baseline.rs').write_text(out)
row=watch[watch.index('pub struct WatchRow'):watch.index('#[derive(Clone, Copy, Debug, PartialEq, Eq)]')]
row=row.replace('pub struct WatchRow','#[derive(Debug)]\npub struct WatchRow',1)
col=watch[watch.index('#[derive(Clone, Copy, Debug, PartialEq, Eq)]'):watch.index('pub struct WatchTable')]
rows=block(watch,'pub fn rows(')
sort=block(watch,'    fn apply_sort(&mut self)')
w='''// Production row construction and sorting, without GPUI integration.
use super::*;
'''+row+col+'''pub struct Table {pub rows:Vec<WatchRow>,sort:Option<(WatchColumn,ColumnSort)>}
impl Table {
'''+sort+'''
 pub fn from_playlist(p:&PlaylistView,f:Option<Summary>,q:&HashSet<ItemId>,column:usize,descending:bool)->Self {
 let c=WatchColumn::at(column).unwrap();
 let mut t=Self {rows:rows(p,f,q),sort:Some((c,if descending{ColumnSort::Descending}else{ColumnSort::Ascending}))};t.apply_sort();t
 }
}
'''+rows
Path('@LAB@/src/watch_baseline.rs').write_text(w)
req=(root/'apps/gui/src/requests.rs').read_text()
Path('@LAB@/src/read_enum.rs').write_text(req[req.index('#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]'):req.index('\nimpl Read')])
print('Extracted production kernels. No repository files changed.')
